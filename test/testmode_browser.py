# 테스트 모드(로고 7번) 시험: python3 test/testmode_browser.py
import os
from playwright.sync_api import sync_playwright
SHOTS = os.environ.get('SHOTS', '/tmp/claude-0/shots')
url = 'file://' + os.path.abspath('index.html')
errs, fails = [], []
def ok(c, m):
    print(('✓ ' if c else '✗ ') + m)
    if not c: fails.append(m)
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1440, 'height': 860})
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(url); pg.wait_for_timeout(600); pg.click('#hOk')
    pg.evaluate("() => { S.ores[0] = 77; S.sessions = 5; save(); }")
    for i in range(5): pg.click('.brand')
    ok(not pg.evaluate('() => TEST.on'), '5번으로는 안 열림')
    pg.wait_for_timeout(900)
    for i in range(7): pg.click('.brand')
    ok(pg.evaluate('() => TEST.on') and pg.is_visible('#testPanel') and pg.is_visible('#testBadge'), '빠르게 7번 누르면 테스트 모드와 패널이 열림')
    ok(pg.evaluate('() => S.ores[0] === 77 && S.run === null'), '진짜 게임 상태를 복사해 오되 랭킹 도전 정보는 뺌')
    pg.click('[data-do="ore"]'); pg.click('[data-do="depthAll"]'); pg.click('[data-do="picks"]'); pg.click('[data-do="level"]')
    st = pg.evaluate('() => ({ore: S.ores[9], depth: MG.depthOf(S), pick: S.picks.eq, pts: S.pts})')
    ok(st['ore'] >= 1000 and st['depth'] == 9 and st['pick'] == 'p10' and st['pts'] >= 1, '광석·광맥·곡괭이·레벨 버튼 ' + str(st))
    pg.click('[data-tg="noFog"]'); pg.wait_for_timeout(1300)
    ok(pg.locator('.mn.ghost').count() == 0 and pg.locator('.mn').count() == pg.evaluate('() => MG.NODES.length'), '안개 걷기: 모든 칸이 보임 (' + str(pg.locator('.mn').count()) + ')')
    pg.screenshot(path=f'{SHOTS}/40-testmode.png')
    pg.click('[data-tg="oneHit"]'); pg.click('[data-tg="endless"]'); pg.click('[data-sp="2"]')
    pg.click('[data-do="heart"]')
    pg.keyboard.press('Space'); pg.wait_for_timeout(400)
    ok(pg.inner_text('#tLeft') == '∞', '시간 무한이면 ∞ 표시')
    box = pg.locator('#cv').bounding_box()
    pg.mouse.move(box['x'] + box['width'] / 2, box['y'] + 70 + (box['height'] - 70) / 2)
    pg.wait_for_timeout(2500)
    pg.screenshot(path=f'{SHOTS}/41-testmode-mine.png')
    ok(pg.evaluate('() => S.cleared'), '한 방에 깨기로 심장도 바로 깨짐')
    ok(pg.is_visible('#clearBox') and '테스트 모드라' in pg.inner_text('#clearBox'), '클리어 화면에 랭킹 안 올라간다고 나옴')
    pg.click('#clearOk'); pg.wait_for_timeout(300)
    for i in range(7): pg.click('.brand')
    ok(not pg.evaluate('() => TEST.on') and not pg.is_visible('#testPanel'), '로고 7번 다시 누르면 닫힘')
    real = pg.evaluate('() => ({ore: S.ores[0], depth: MG.depthOf(S), cleared: S.cleared})')
    ok(real['ore'] == 77 and real['depth'] == 0 and not real['cleared'], '진짜 게임은 그대로 ' + str(real))
    pg.reload(); pg.wait_for_timeout(500)
    ok(not pg.evaluate('() => TEST.on') and pg.evaluate('() => S.ores[0]') == 77, '새로고침하면 진짜 게임으로 열림')
    for i in range(7): pg.click('.brand')
    ok(pg.evaluate('() => TEST.on && S.cleared && MG.depthOf(S) === 9'), '다시 열면 테스트판이 이어짐')
    pg.click('[data-a="exit"]')
    ok(not pg.evaluate('() => TEST.on'), '나가기 버튼')
    b.close()
print('오류', errs)
print('실패' if fails else '모두 통과', len(fails))
