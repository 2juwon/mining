// 로컬 서버 시험: cd server && npx wrangler dev --var FAST_TEST:1 --var ADMIN_KEY:test  →  node test/rank.test.mjs
const BASE = process.env.BASE || 'http://127.0.0.1:8787';
let fails = 0, n = 0;
const ok = (c, m) => { n++; if (!c) { fails++; console.log('✗', m); } else console.log('✓', m); };
const post = (p, b, h = {}) => fetch(BASE + p, { method: 'POST', headers: { 'content-type': 'application/json', ...h }, body: JSON.stringify(b || {}) }).then(async (r) => ({ status: r.status, ...(await r.json()) }));
const get = (p, h = {}) => fetch(BASE + p, { headers: h }).then(async (r) => ({ status: r.status, ...(await r.json()) }));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const a = await post('/api/run/start');
ok(a.run && a.token && a.at, '새 게임 시작하면 도전 번호·열쇠를 줌');
const bad = await post('/api/run/clear', { run: a.run, token: 'x' + a.token.slice(1), sessions: 50 });
ok(bad.error, '열쇠가 틀리면 거절');
const early = await post('/api/run/start');
const e1 = await post('/api/run/clear', { run: early.run, token: early.token, sessions: 50 });
ok(e1.error && /빨라서/.test(e1.error), '1초 안에 깬 기록은 너무 빠르다고 거절');
const e2 = await post('/api/run/name', { run: early.run, token: early.token, name: '반칙' });
ok(e2.error, '거절된 기록은 이름을 올릴 수 없음');
await sleep(1300);
const nn = await post('/api/run/name', { run: a.run, token: a.token, name: '광부' });
ok(nn.error && /아직/.test(nn.error), '깨기 전에는 이름을 올릴 수 없음');
const c1 = await post('/api/run/clear', { run: a.run, token: a.token, sessions: 50, level: 19, broken: 3000, clientMs: 1 });
ok(c1.ok && c1.ms >= 1300 && c1.ms < 5000, '서버 시계로 걸린 시간을 잼 (화면이 보낸 시간은 무시) ' + c1.ms);
ok(c1.place === 1, '예상 순위 1위');
await sleep(300);
const c2 = await post('/api/run/clear', { run: a.run, token: a.token, sessions: 50 });
ok(c2.ms === c1.ms, '다시 알려도 처음 잰 시간 그대로');
const n1 = await post('/api/run/name', { run: a.run, token: a.token, name: '  <금광>   캐는 사람이름이길어요 ' });
ok(n1.ok && n1.place === 1, '이름 올림');
const n2 = await post('/api/run/name', { run: a.run, token: a.token, name: '또' });
ok(n2.error, '같은 기록은 한 번만');
const b2 = await post('/api/run/start');
await sleep(1500);
await post('/api/run/clear', { run: b2.run, token: b2.token, sessions: 60, level: 20 });
const n3 = await post('/api/run/name', { run: b2.run, token: b2.token, name: '둘째' });
ok(n3.ok && n3.place === 2, '더 오래 걸린 기록은 2위');
const board = await get('/api/rank');
ok(board.list.length >= 2 && board.list.some((e) => e.name === '금광 캐는 사람') && board.list[0].ms <= board.list[1].ms, '랭킹: 이름 다듬기(8자, 기호 빼기)와 시간 순서 ' + board.list.map((e) => e.name).join(','));
ok(board.starts >= 3 && board.clears >= 2, '시작·클리어 횟수 ' + board.starts + '/' + board.clears);
const adm0 = await get('/api/admin/rank', { 'x-admin-key': 'nope' });
ok(adm0.status === 401, '관리자 비밀번호 틀리면 거절');
const adm = await get('/api/admin/rank', { 'x-admin-key': 'test' });
ok(adm.list && adm.list.length >= 2, '관리 페이지에서 랭킹 보기');
const del = await fetch(BASE + '/api/admin/rank/' + adm.list[1].id, { method: 'DELETE', headers: { 'x-admin-key': 'test' } }).then((r) => r.json());
ok(del.ok, '관리자가 기록 지우기');
const fb = await get('/api/admin/feedback', { 'x-admin-key': 'test' });
ok(fb.items.some((i) => /너무 빠른 클리어/.test(i.text)), '너무 빠른 기록은 의견함에 자동 신고');
const f = await post('/api/feedback', { kind: 'idea', text: '재밌어요' });
ok(f.ok, '의견 보내기');
console.log(`\n${n - fails}/${n} 통과`);
process.exit(fails ? 1 : 0);
